/* sdl_min.h against SDL's own headers (the Steam Runtime SDK has SDL 3 and SDL3_ttf): every value,
 * layout and function type the crash window takes from it. Compiled, never run, by
 * scripts/build-native-host-linux.sh; a difference fails the build. */
#include <SDL3/SDL.h>
#include <SDL3_ttf/SDL_ttf.h>
#include "sdl_min.h"

#define SAME(a, b) _Static_assert((unsigned long long)(a) == (unsigned long long)(b), #a)
#define AT(ours, theirs, field) _Static_assert(offsetof(ours, field) == offsetof(theirs, field), #ours "." #field)

SAME(MS_SDL_INIT_VIDEO, SDL_INIT_VIDEO); SAME(MS_SDL_INIT_GAMEPAD, SDL_INIT_GAMEPAD);
SAME(MS_SDL_EVENT_QUIT, SDL_EVENT_QUIT); SAME(MS_SDL_EVENT_SYSTEM_THEME_CHANGED, SDL_EVENT_SYSTEM_THEME_CHANGED);
SAME(MS_SDL_EVENT_WINDOW_SHOWN, SDL_EVENT_WINDOW_SHOWN); SAME(MS_SDL_EVENT_WINDOW_EXPOSED, SDL_EVENT_WINDOW_EXPOSED);
SAME(MS_SDL_EVENT_WINDOW_RESIZED, SDL_EVENT_WINDOW_RESIZED); SAME(MS_SDL_EVENT_WINDOW_PIXEL_SIZE_CHANGED, SDL_EVENT_WINDOW_PIXEL_SIZE_CHANGED);
SAME(MS_SDL_EVENT_WINDOW_MOUSE_LEAVE, SDL_EVENT_WINDOW_MOUSE_LEAVE); SAME(MS_SDL_EVENT_WINDOW_FOCUS_GAINED, SDL_EVENT_WINDOW_FOCUS_GAINED);
SAME(MS_SDL_EVENT_WINDOW_FOCUS_LOST, SDL_EVENT_WINDOW_FOCUS_LOST); SAME(MS_SDL_EVENT_WINDOW_CLOSE_REQUESTED, SDL_EVENT_WINDOW_CLOSE_REQUESTED);
SAME(MS_SDL_EVENT_WINDOW_DISPLAY_SCALE_CHANGED, SDL_EVENT_WINDOW_DISPLAY_SCALE_CHANGED);
SAME(MS_SDL_EVENT_KEY_DOWN, SDL_EVENT_KEY_DOWN); SAME(MS_SDL_EVENT_KEY_UP, SDL_EVENT_KEY_UP);
SAME(MS_SDL_EVENT_TEXT_EDITING, SDL_EVENT_TEXT_EDITING); SAME(MS_SDL_EVENT_TEXT_INPUT, SDL_EVENT_TEXT_INPUT);
SAME(MS_SDL_EVENT_MOUSE_MOTION, SDL_EVENT_MOUSE_MOTION); SAME(MS_SDL_EVENT_MOUSE_BUTTON_DOWN, SDL_EVENT_MOUSE_BUTTON_DOWN);
SAME(MS_SDL_EVENT_MOUSE_BUTTON_UP, SDL_EVENT_MOUSE_BUTTON_UP); SAME(MS_SDL_EVENT_MOUSE_WHEEL, SDL_EVENT_MOUSE_WHEEL);
SAME(MS_SDL_EVENT_GAMEPAD_BUTTON_DOWN, SDL_EVENT_GAMEPAD_BUTTON_DOWN); SAME(MS_SDL_EVENT_GAMEPAD_ADDED, SDL_EVENT_GAMEPAD_ADDED);
SAME(MS_SDLK_RETURN, SDLK_RETURN); SAME(MS_SDLK_ESCAPE, SDLK_ESCAPE); SAME(MS_SDLK_BACKSPACE, SDLK_BACKSPACE); SAME(MS_SDLK_TAB, SDLK_TAB);
SAME(MS_SDLK_SPACE, SDLK_SPACE); SAME(MS_SDLK_DELETE, SDLK_DELETE); SAME(MS_SDLK_LEFT, SDLK_LEFT); SAME(MS_SDLK_RIGHT, SDLK_RIGHT);
SAME(MS_SDLK_UP, SDLK_UP); SAME(MS_SDLK_DOWN, SDLK_DOWN); SAME(MS_SDLK_HOME, SDLK_HOME); SAME(MS_SDLK_END, SDLK_END);
SAME(MS_SDLK_A, SDLK_A); SAME(MS_SDLK_C, SDLK_C); SAME(MS_SDLK_V, SDLK_V); SAME(MS_SDLK_X, SDLK_X); SAME(MS_SDLK_KP_ENTER, SDLK_KP_ENTER);
SAME(MS_SDL_KMOD_SHIFT, SDL_KMOD_SHIFT); SAME(MS_SDL_KMOD_CTRL, SDL_KMOD_CTRL); SAME(MS_SDL_KMOD_ALT, SDL_KMOD_ALT);
SAME(MS_SDL_BUTTON_LEFT, SDL_BUTTON_LEFT); SAME(MS_SDL_WINDOW_HIDDEN, SDL_WINDOW_HIDDEN);
SAME(MS_SDL_WINDOW_HIGH_PIXEL_DENSITY, SDL_WINDOW_HIGH_PIXEL_DENSITY); SAME(MS_SDL_WINDOWPOS_CENTERED, SDL_WINDOWPOS_CENTERED);
