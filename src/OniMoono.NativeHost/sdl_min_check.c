_Static_assert(sizeof(MS_Event) == sizeof(SDL_Event), "SDL_Event");
_Static_assert(sizeof(MS_Surface) == sizeof(SDL_Surface), "SDL_Surface");
AT(MS_Surface, SDL_Surface, flags); AT(MS_Surface, SDL_Surface, format); AT(MS_Surface, SDL_Surface, w); AT(MS_Surface, SDL_Surface, h);
AT(MS_Surface, SDL_Surface, pitch); AT(MS_Surface, SDL_Surface, pixels);
_Static_assert(sizeof(MS_Rect) == sizeof(SDL_Rect) && sizeof(MS_Color) == sizeof(SDL_Color), "SDL_Rect, SDL_Color");
AT(MS_WindowEvent, SDL_WindowEvent, data1); AT(MS_WindowEvent, SDL_WindowEvent, data2);
AT(MS_KeyboardEvent, SDL_KeyboardEvent, key); AT(MS_KeyboardEvent, SDL_KeyboardEvent, mod); AT(MS_KeyboardEvent, SDL_KeyboardEvent, down);
AT(MS_KeyboardEvent, SDL_KeyboardEvent, repeat);
AT(MS_TextInputEvent, SDL_TextInputEvent, text);
AT(MS_MouseMotionEvent, SDL_MouseMotionEvent, x); AT(MS_MouseMotionEvent, SDL_MouseMotionEvent, y); AT(MS_MouseMotionEvent, SDL_MouseMotionEvent, state);
AT(MS_MouseButtonEvent, SDL_MouseButtonEvent, button); AT(MS_MouseButtonEvent, SDL_MouseButtonEvent, down);
AT(MS_MouseButtonEvent, SDL_MouseButtonEvent, clicks); AT(MS_MouseButtonEvent, SDL_MouseButtonEvent, x); AT(MS_MouseButtonEvent, SDL_MouseButtonEvent, y);
AT(MS_MouseWheelEvent, SDL_MouseWheelEvent, x); AT(MS_MouseWheelEvent, SDL_MouseWheelEvent, y);
AT(MS_GamepadButtonEvent, SDL_GamepadButtonEvent, which); AT(MS_GamepadButtonEvent, SDL_GamepadButtonEvent, button);
AT(MS_GamepadDeviceEvent, SDL_GamepadDeviceEvent, which);

