SAME(MS_SDL_SYSTEM_CURSOR_WAIT, SDL_SYSTEM_CURSOR_WAIT); SAME(MS_SDL_SYSTEM_CURSOR_POINTER, SDL_SYSTEM_CURSOR_POINTER);
SAME(MS_SDL_SYSTEM_THEME_LIGHT, SDL_SYSTEM_THEME_LIGHT); SAME(MS_SDL_SYSTEM_THEME_DARK, SDL_SYSTEM_THEME_DARK);
SAME(MS_SDL_GAMEPAD_BUTTON_SOUTH, SDL_GAMEPAD_BUTTON_SOUTH); SAME(MS_SDL_GAMEPAD_BUTTON_EAST, SDL_GAMEPAD_BUTTON_EAST);
