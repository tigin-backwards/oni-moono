#!/usr/bin/env python3
"""Writes src/OniMoono.NativeHost/dxbc_check.cpp from the DXBC token-format constants the asset
reader uses (src/OniMoono.Assets/Shaders/DxbcTokenFormat.cs): one static_assert per constant
against microsoft/DirectX-Headers' D3D12TokenizedProgramFormat.hpp (src/ThirdParty/DirectX-Headers)
or, for D3D_* names, the Windows SDK's d3dcommon.h. A constant named as in a header is compared
with that name; any other carries its header expression in a trailing `// = EXPR` comment.
Compiled, never run: by the Windows build (src/OniMoono.NativeHost/build.cmd, MSVC with the SDK)
and by tests/scripts/test_dxbc_check.py, which also checks that the committed file is this
script's output.

    scripts/gen-dxbc-check.py            rewrite the committed file
    scripts/gen-dxbc-check.py --stdout   print it instead
"""

import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SOURCE = os.path.join(ROOT, "src", "OniMoono.Assets", "Shaders", "DxbcTokenFormat.cs")
OUTPUT = os.path.join(ROOT, "src", "OniMoono.NativeHost", "dxbc_check.cpp")

STATEMENT = re.compile(r"public const (?:int|uint) (.*?);[ \t]*(?://[ \t]*=[ \t]*([^\n]*))?$", re.S | re.M)
DECLARATOR = re.compile(r"^\s*(\w+)\s*=\s*(0x[0-9A-Fa-f]+|\d+)\s*$")


def constants(text):
    """(name, value, header expression) of every constant of the C# file."""
    found = []
    for statement in STATEMENT.finditer(text):
        body, expression = statement.group(1), statement.group(2)
        declarators = body.split(",")
        if expression is not None and len(declarators) != 1:
            raise ValueError(f"a `// = EXPR` comment on several constants: {body.strip()}")
        for declarator in declarators:
            m = DECLARATOR.match(declarator)
            if not m:
                raise ValueError(f"not a constant this script reads: {declarator.strip()}")
            name, value = m.groups()
            if expression is None and not name.startswith(("D3D10_", "D3D11_", "D3D_")):
                raise ValueError(f"{name}: neither a header name nor a `// = EXPR` comment")
            found.append((name, value, expression.strip() if expression else name))
    return found


def generate(text):
    lines = [
        "// Generated by scripts/gen-dxbc-check.py from src/OniMoono.Assets/Shaders/DxbcTokenFormat.cs;",
        "// do not edit. Compiled, never run (build.cmd; tests/scripts/test_dxbc_check.py): every value",
        "// the DXBC reader uses must equal D3D12TokenizedProgramFormat.hpp's (microsoft/DirectX-Headers",
        "// 61c7718954ec73dbdd43c723240fe1a0452a3724) or, for D3D_*, the Windows SDK's d3dcommon.h.",
        "#ifdef _WIN32",
        "#include <windows.h>",
        "#include <d3dcommon.h>",
        "#endif",
        '#include "D3D12TokenizedProgramFormat.hpp"',
        "",
        "#define SAME(ours, theirs) static_assert((unsigned long long)(ours) == (unsigned long long)(theirs), #theirs)",
        "",
    ]
    sdk = []
    for name, value, expression in constants(text):
        line = f"SAME({value}, {expression});"
        (sdk if name.startswith("D3D_") else lines).append(line)
    if sdk:
        lines += ["", "#ifdef _WIN32", *sdk, "#endif"]
    return "\n".join(lines) + "\n"


def main(argv):
    with open(SOURCE, encoding="utf-8") as f:
        out = generate(f.read())
    if "--stdout" in argv:
        sys.stdout.write(out)
        return 0
    with open(OUTPUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(out)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
