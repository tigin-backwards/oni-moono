#!/usr/bin/env python3
"""Refreshes the Sigstore trusted root embedded in Moono (src/OniMoono.Host/Install/SigstoreTrustedRoot.cs),
which the installer verifies the Workshop item's attestation against (docs/INSTALL-MODES.md).

    scripts/sigstore-trusted-root.py            from `gh attestation trusted-root`
    scripts/sigstore-trusted-root.py --from F   from a trusted_root.json or that command's output

`gh attestation trusted-root` fetches Sigstore's TUF repository and checks it against the root
of trust built into gh, so what it prints is what gh itself verifies with. Of its lines only
the public-good instance's is kept (Fulcio fulcio.sigstore.dev, Rekor rekor.sigstore.dev),
which signs the attestations of a public repository; GitHub's own instance is for private ones.
Refresh it when Sigstore adds or rotates a key (a new Fulcio intermediate, Rekor shard key or CT
log), before an item signed under the new key is uploaded: a player with the old root refuses
such an item, and only a fresh first start from the item (or a release's setup) brings it the new
root.
"""

import argparse
import datetime
import json
import os
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "src", "OniMoono.Host", "Install", "SigstoreTrustedRoot.cs")
PUBLIC_GOOD = "https://fulcio.sigstore.dev"

HEADER = """#nullable enable
namespace OniMoono.Host.Install
{
    /// Sigstore's public-good trusted root (Fulcio, Rekor, CT logs), as `gh attestation
    /// trusted-root` printed it on %s. Generated by scripts/sigstore-trusted-root.py: refresh with
    /// it, never by hand (docs/INSTALL-MODES.md, "What the installer verifies").
    internal static class SigstoreTrustedRoot
    {
        public const string Json = \"\"\"
"""

FOOTER = """
            \"\"\";
    }
}
"""


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--from", dest="source")
    args = parser.parse_args()
    if args.source:
        with open(args.source, encoding="utf-8") as f:
            text = f.read()
    else:
        text = subprocess.run(["gh", "attestation", "trusted-root"], check=True, capture_output=True, text=True).stdout
    roots = []
    stripped = text.strip()
    if stripped.startswith("{") and "\n{" not in stripped:
        roots.append(json.loads(stripped))
    else:
        roots.extend(json.loads(line) for line in text.splitlines() if line.strip())
    chosen = [r for r in roots if any(ca.get("uri") == PUBLIC_GOOD for ca in r.get("certificateAuthorities", []))]
    if len(chosen) != 1:
        sys.exit(f"sigstore-trusted-root: expected one public-good root, found {len(chosen)}")
    root = chosen[0]
    for key in ("certificateAuthorities", "tlogs", "ctlogs"):
        if not root.get(key):
            sys.exit(f"sigstore-trusted-root: the root has no {key}")
    body = json.dumps(root, indent=2, sort_keys=False)
    if '"""' in body:
        sys.exit("sigstore-trusted-root: the root can't go in a raw string literal")
    today = datetime.date.today().isoformat()
    lines = "\n".join(("            " + line) if line else line for line in body.splitlines())
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(HEADER % today + lines + FOOTER)
    print(f"{os.path.relpath(OUT, ROOT)}: {len(root['certificateAuthorities'])} authorities, {len(root['tlogs'])} tlogs, {len(root['ctlogs'])} CT logs")


if __name__ == "__main__":
    main()
